/// Path to the PID file.
pub(crate) fn pid_path() -> PathBuf {
    config_dir().join("cerberus.pid")
}

fn endpoint_path() -> PathBuf {
    config_dir().join(ENDPOINT_FILE)
}

fn persist_endpoint(actual: std::net::SocketAddr, pid: u32) -> Result<(), String> {
    let endpoint = ControlPlaneEndpoint::new(&actual.to_string(), pid).map_err(|e| e.to_string())?;
    let target = endpoint_path();
    let tmp = target.with_extension(format!("json.tmp-{pid}"));
    fs::write(&tmp, endpoint.to_json().map_err(|e| e.to_string())?)
        .map_err(|e| format!("cannot write endpoint metadata: {e}"))?;
    if let Err(first) = fs::rename(&tmp, &target) {
        // Windows does not replace an existing target with rename. A stale
        // descriptor is not authoritative (the PID file is), so it is removed
        // and retried with the temp fully written.
        if target.exists() {
            fs::remove_file(&target).map_err(|e| format!("cannot replace stale endpoint metadata: {e}"))?;
            fs::rename(&tmp, &target).map_err(|e| format!("cannot publish endpoint metadata: {e}"))?;
        } else {
            let _ = fs::remove_file(&tmp);
            return Err(format!("cannot publish endpoint metadata: {first}"));
        }
    }
    Ok(())
}

fn remove_runtime_files() {
    let _ = fs::remove_file(pid_path());
    let _ = fs::remove_file(endpoint_path());
}

/// Path to the configuration directory (delegated to `platform` so that on
/// Windows it is `%APPDATA%\Cerberus` instead of `~\.cerberus`).
pub(crate) fn config_dir() -> std::path::PathBuf {
    platform::config_dir()
}

/// Path to the YAML config file generated by `cerberus init`.
fn config_file() -> PathBuf {
    config_dir().join("config.yaml")
}

/// Path to the installed rule packs directory (`~/.cerberus/packs`).
pub(crate) fn packs_dir() -> PathBuf {
    config_dir().join("packs")
}

/// Path to the active license file: env `CERBERUS_LICENSE_PATH` or, by
/// default, `~/.cerberus/license.json`.
pub(crate) fn license_path() -> PathBuf {
    std::env::var("CERBERUS_LICENSE_PATH")
        .ok()
        .filter(|p| !p.is_empty())
        .map_or_else(|| config_dir().join("license.json"), PathBuf::from)
}

/// Load the active license for the daemon (F7 connection in the product,
/// fix from code review item 12).
///
/// **Product fail-open policy**: if the file does not exist or verification
/// fails (no trust root or invalid signature), it continues with Free tier
/// and logs a clear warning. The license only gates Pro features (open-core:
/// the engine and the basic local mode remain free, §7 of the plan).
pub(crate) fn load_license(path: Option<&std::path::Path>) -> LicenseManager {
    let Some(path) = path else {
        return LicenseManager::free();
    };
    if !path.exists() {
        return LicenseManager::free();
    }
    match LicenseManager::from_file(path) {
        Ok(mgr) => mgr,
        Err(e) => {
            tracing::warn!(
                "license load failed ({e}); continuing with Free tier (fail-open) — set \
                 CERBERUS_LICENSE_PUBLIC_KEY and a valid license at CERBERUS_LICENSE_PATH"
            );
            LicenseManager::free()
        }
    }
}

/// License summary for the boot log, with the machine-readable
/// `tier=pro|free` field (key for the integration test).
#[must_use]
pub(crate) fn license_summary(mgr: &LicenseManager) -> String {
    let tier = if mgr.is_pro() { "pro" } else { "free" };
    let state = if mgr.is_expired() { "expired" } else { "valid" };
    format!("tier={tier} state={state}\n{}", mgr.report())
}

/// Try to load YAML config from `cerberus init`.
/// Returns `None` if the file does not exist or is invalid.
fn load_proxy_config() -> Option<ProxyConfig> {
    load_proxy_config_from(&config_file())
}

/// Load config from an explicit path to isolate the filesystem in tests.
///
/// Fix P3-1 (attempt 2): a config file that EXISTS but fails to parse is
/// never silently swallowed — the real serde error is logged loudly (the
/// operator previously saw the misleading `no upstreams configured` instead).
/// The behavior stays fail-closed: the invalid file is ignored and the
/// defaults apply (or boot refuses where required).
fn load_proxy_config_from(path: &std::path::Path) -> Option<ProxyConfig> {
    if !path.exists() {
        return None;
    }
    match ProxyConfig::from_file(path) {
        Ok(cfg) => Some(cfg),
        Err(e) => {
            tracing::error!(
                "proxy config file {} is INVALID and will be IGNORED (fail-closed defaults apply — fix the parse error or remove the file): {e}",
                path.display()
            );
            None
        }
    }
}

/// Resolve the per-installation audit-hash key (R9-16, F5.2).
///
/// Precedence: `CERBERUS_HMAC_SECRET` env override → persisted key file →
/// generate + persist (0600, atomic). There is NO unkeyed fallback: every
/// hash of secret material in the product is keyed HMAC-SHA256. See
/// `audit_key.rs` for the full key-management design.
pub(crate) fn resolve_audit_key() -> (Vec<u8>, crate::audit_key::KeySource) {
    crate::audit_key::resolve_or_create_key(&crate::audit_key::default_config_dir())
}

/// Non-empty env value as `Option<String>`.
fn env_nonempty(name: &str) -> Option<String> {
    std::env::var(name).ok().filter(|s| !s.is_empty())
}

/// Audit retention days: env `CERBERUS_RETENTION_DAYS` (default 90). `0` =
/// minimum retention (see `store::purge_old`).
fn retention_days_from_env() -> u64 {
    std::env::var("CERBERUS_RETENTION_DAYS")
        .ok()
        .and_then(|s| s.trim().parse::<u64>().ok())
        .unwrap_or(90)
}

/// Compile the base engine (default rules + the installation payload-hash
/// key — ALWAYS keyed, R9-16/F5.2).
/// This is the ONLY source of rules for the daemon and the CLI: from here
/// derives both the `PackManager` (which merges it with the packs, finding 7)
/// and the snapshot the proxy receives — without a second independent
/// compilation.
///
/// # Errors
///
/// Returns the error from loading/compiling the rules.
fn build_base_engine(audit_key: &[u8]) -> Result<cerberus_engine::engine::CompiledEngine, String> {
    let rules_json = default_rules_json();
    let rules = load_rules_from_str(&rules_json).map_err(|e| format!("error loading rules: {e}"))?;
    EngineBuilder::new(&rules)
        .with_payload_secret(audit_key.to_vec())
        .build()
        .map_err(|e| format!("engine build error: {e}"))
}

/// Open a `PackManager` over `packs_dir()` with the base engine — the SAME
/// for the daemon and the CLI (finding 7: there is no second engine).
///
/// # Errors
///
/// Returns an error if the packs directory cannot be created or compilation fails.
fn open_packs_manager(audit_key: &[u8]) -> Result<PackManager, String> {
    let engine = build_base_engine(audit_key)?;
    let license = load_license(Some(&license_path()));
    let trust_root =
        PackTrustRoot::from_optional_key(env_nonempty("CERBERUS_PACK_TRUST_ROOT")).gated_by_pro(license.is_pro());
    PackManager::open(packs_dir(), engine, &trust_root).map_err(|e| format!("packs setup error: {e}"))
}

// ─────────────────────────────────────────────────────────────────────────────
// A) Real MERGE of the config: base = config.yaml (fail_policy, max_body_bytes,
//    health_path, log_level, etc. ALL preserved — see the fix from code review
//    v4 finding 5, daemon part: previously it was reconstructed with
//    `..default()` and those YAML fields were lost).
//
// Precedence:
//   listen      env `CERBERUS_LISTEN_HOST` (or host from file_cfg) + CLI port.
//   upstreams   env `CERBERUS_UPSTREAMS` (JSON) > env `CERBERUS_UPSTREAM_URL`
//               (openai/anthropic/default) > config.yaml > instructive error.
//   admin_token env `CERBERUS_ADMIN_TOKEN` > config.yaml.
//   mode        env `CERBERUS_MODE` > config.yaml.
// ─────────────────────────────────────────────────────────────────────────────
fn resolve_config(port: u16, file_cfg: Option<ProxyConfig>) -> Result<ProxyConfig, String> {
    let mut config = file_cfg.unwrap_or_default();

    // Mode: env > file.
    if let Some(mode_raw) = env_nonempty("CERBERUS_MODE") {
        config.mode = serde_yaml::from_str::<OperationMode>(&mode_raw)
            .or_else(|_| serde_json::from_str::<OperationMode>(&mode_raw))
            .map_err(|e| format!("invalid CERBERUS_MODE ('{mode_raw}'): {e}"))?;
    }

    // Listen: host from env (0.0.0.0 in Docker) or the file's host; the
    // port is ALWAYS the CLI's (default 8787).
    let listen_host = std::env::var("CERBERUS_LISTEN_HOST")
        .ok()
        .filter(|h| !h.is_empty())
        .unwrap_or_else(|| {
            config
                .listen
                .split(':')
                .next()
                .map(str::to_string)
                .filter(|h| !h.is_empty())
                .unwrap_or_else(|| "127.0.0.1".to_string())
        });
    config.listen = format!("{listen_host}:{port}");

    // Upstreams: env (JSON) > env URL (openai/anthropic/default) > file.
    // With no upstream → error with clear instructions.
    let upstream_auth = "authorization".to_string();
    if let Some(upstreams_json) = env_nonempty("CERBERUS_UPSTREAMS") {
        config.upstreams = serde_json::from_str::<HashMap<String, UpstreamConfig>>(&upstreams_json)
            .map_err(|e| format!("invalid CERBERUS_UPSTREAMS JSON: {e}"))?;
    } else if let Some(url) = env_nonempty("CERBERUS_UPSTREAM_URL") {
        // P1 #7 compat: the base URL creates MULTIPLE upstreams so that
        // prefix-based routing works (openai/anthropic/default).
        let mut m = HashMap::new();
        m.insert(
            "openai".to_string(),
            UpstreamConfig {
                url: url.clone(),
                path_prefix: Some("/openai/".to_string()),
                auth_header: upstream_auth.clone(),
                mode: None,
                expected_auth: None,
            },
        );
        m.insert(
            "anthropic".to_string(),
            UpstreamConfig {
                url: url.clone(),
                path_prefix: Some("/anthropic/".to_string()),
                auth_header: upstream_auth.clone(),
                mode: None,
                expected_auth: None,
            },
        );
        m.insert(
            "default".to_string(),
            UpstreamConfig {
                url,
                path_prefix: None,
                auth_header: upstream_auth,
                mode: None,
                expected_auth: None,
            },
        );
        config.upstreams = m;
    }

    if config.upstreams.is_empty() {
        return Err("no upstreams configured: run 'cerberus init' or export CERBERUS_UPSTREAM_URL".to_string());
    }

    // Admin token: env takes priority, then config.yaml (control plane P0).
    if let Some(token) = env_nonempty("CERBERUS_ADMIN_TOKEN") {
        config.admin_token = Some(token);
    }

    Ok(config)
}

#[allow(
    clippy::too_many_lines,
    clippy::option_if_let_else,
    clippy::map_unwrap_or,
    clippy::if_not_else
)]
pub(crate) async fn start(port: u16, chain: Option<String>) -> Result<String, String> {
    // Check if already running
    if is_running() {
        return Err("Cerberus is already running. Use 'cerberus stop' first.".to_string());
    }

    // R9-16 (F5.2): resolve the per-installation audit-hash key ONCE per
    // boot and thread it through EVERY engine construction + the API context,
    // so all secret-material hashes (event hashes, entropy, break-glass
    // reasons) share one keyed, domain-separated scheme.
    let (audit_key, key_source) = resolve_audit_key();
    println!("audit hashing: keyed HMAC-SHA256 (key source: {})", key_source.label());

    // UNIQUE base engine (finding 7): used by PackManager and, after the
    // initial pack load, by the snapshot the proxy receives.
    let base_engine = build_base_engine(&audit_key)?;

    // A) Real config: base = config.yaml (without losing fields) + overrides.
    let file_cfg = load_proxy_config();
    let mut config = resolve_config(port, file_cfg)?;

    // --chain: rewrite all upstreams to forward to another local proxy
    // (e.g. headroom) instead of the provider directly. This lets you
    // stack Cerberus (DLP) → headroom (compression) → provider.
    if let Some(ref chain_url) = chain {
        let chain_url = chain_url.trim_end_matches('/');
        for up in config.upstreams.values_mut() {
            up.url = chain_url.to_string();
        }
        println!("chain: all upstreams → {chain_url}");
    }
    // A missing/disabled `mitm.json` produces `None`: the reverse proxy
    // remains always the default. If the user explicitly opted into MITM, we
    // validate CA/hosts/listener before initializing the daemon.
    let mitm_config = crate::mitm::runtime_config()?;

    // C/F) Audit with configurable retention (env, default 90 days).
    let retention_days = retention_days_from_env();
    let db_path = pid_path()
        .parent()
        .map_or_else(|| PathBuf::from("/tmp/cerberus/cerberus.db"), |p| p.join("cerberus.db"));
    fs::create_dir_all(config_dir()).map_err(|e| format!("cannot create config dir: {e}"))?;

    let store_opt = AuditStore::open_with(&db_path, retention_days).map(Arc::new).ok();
    if store_opt.is_some() {
        println!(
            "Audit store opened at {} (retention {retention_days} days)",
            db_path.display()
        );
    } else {
        eprintln!("warning: audit store unavailable — events will be in-memory only");
    }

    println!(
        "effective config: mode={} fail_policy={} max_body_bytes={} health_path={}",
        format!("{:?}", config.mode).to_lowercase(),
        format!("{:?}", config.fail_policy).to_lowercase(),
        config.max_body_bytes.unwrap_or(0),
        config.health_path
    );

    // Shared config proxy ↔ Config API (real hot-reload, P0-5).
    let shared_config = Arc::new(std::sync::RwLock::new(config.clone()));

    // F7: active license (fail-open → Free if not verifiable).
    let boot_license_path = license_path();
    let license: Arc<LicenseManager> = Arc::new(load_license(Some(boot_license_path.as_path())));
    tracing::info!(
        "license: loaded from {} —\n{}",
        boot_license_path.display(),
        license_summary(&license)
    );

    // F7: PackManager over the SAME base engine; we load signed packs already
    // present in `~/.cerberus/packs` (if there is a trust root) BEFORE raising
    // the proxy → the snapshot the proxy receives already includes those packs.
    // F7: PackManager with the SAME base engine. Packs in the dir are hydrated
    // BEFORE raising the proxy (trust root); the initial snapshot feeds the
    // proxy's engine. Runtime hot-reload is managed by a packs WORKER
    // (fix review v5): a shared `Arc<RwLock<Arc<CompiledEngine>>>` with the
    // proxy is atomically swapped on each install/rollback via the
    // `/api/packs/*` routes.
    // The trust root is resolved AFTER the license and disabled in Free tier
    // before constructing the manager. This way no active manifest can
    // hydrate Pro packs during the constructor and evade the boot gate.
    let trust_root =
        PackTrustRoot::from_optional_key(env_nonempty("CERBERUS_PACK_TRUST_ROOT")).gated_by_pro(license.is_pro());
    let packs_manager =
        PackManager::open(packs_dir(), base_engine, &trust_root).map_err(|e| format!("packs setup error: {e}"))?;
    if !trust_root.is_enabled() {
        tracing::warn!("packs: no effective trust root (Free tier or root missing) — base engine, zero packs");
    }
    let engine_for_proxy = packs_manager.snapshot_engine(Some(&audit_key)).await?;
    let installed = packs_manager.list_packs().await.len();
    println!(
        "packs: manager ready at {} ({} packs installed; snapshot passes to the proxy)",
        packs_dir().display(),
        installed
    );

    // Fix review v6.1: the BASE rules of the dataplane are the packs snapshot
    // (defaults + signed packs). The policy persisted in config.yaml
    // (categories, overrides, and custom rules) is applied ON TOP at boot →
    // what the operator saved from the dashboard is restored without having
    // to reinstall anything. If the YAML brings a policy that does not
    // compile, boot fails loudly: we prefer not to boot over booting with
    // less detection than the operator believes they have.
    let base_rules: Vec<cerberus_engine::rule::Rule> = engine_for_proxy.rules().to_vec();
    config
        .policy
        .validate()
        .map_err(|e| format!("invalid policy in {}: {e}", config_file().display()))?;
    let boot_engine = cerberus_proxy::detection_policy::build_engine(&base_rules, &config.policy, Some(&audit_key))
        .map_err(|e| format!("policy engine build error: {e}"))?;
    println!(
        "policy: {} categories, {} overrides, {} custom rules, {} allowlist entries → engine with {} rules ({} base)",
        config.policy.categories.len(),
        config.policy.rule_actions.len(),
        config.policy.custom_rules.len(),
        config.policy.allowlist.len(),
        boot_engine.num_rules(),
        base_rules.len(),
    );

    // Swappable engine (hot-reload): the proxy reads from here; the packs
    // worker writes the snapshot after install/rollback and the control plane
    // republishes after each policy change.
    let live_engine: Arc<RwLock<Arc<CompiledEngine>>> = Arc::new(std::sync::RwLock::new(Arc::new(boot_engine)));
    let engine_control =
        cerberus_proxy::detection_policy::EngineControl::new(live_engine.clone(), base_rules, Some(audit_key.clone()));

    // Rule packs worker (async) — runs install/rollback/list against the
    // PackManager and, after each mutation, replaces the BASE rules and
    // republishes the policy on top → the running proxy changes rules WITHOUT
    // restarting and without losing the operator's custom rules.
    let pack_worker_manager: Arc<PackManager> = Arc::new(packs_manager);
    let (pack_tx, mut pack_rx) = tokio::sync::mpsc::channel::<cerberus_proxy::api::PackCommand>(8);
    let packs_worker_manager = pack_worker_manager.clone();
    let engine_control_worker = engine_control.clone();
    let policy_source = shared_config.clone();
    let audit_key_for_worker = audit_key.clone();
    tokio::spawn(async move {
        use cerberus_proxy::api::PackCommand;
        // The SAME installation key follows hot-reloads (R9-16/F5.2): pack
        // snapshots are compiled keyed exactly like the boot engine.
        let payload_secret = Some(audit_key_for_worker.clone());
        while let Some(cmd) = pack_rx.recv().await {
            // Each arm produces (reply, Result) and the send happens once.
            let outcome: (
                tokio::sync::oneshot::Sender<Result<String, String>>,
                Result<String, String>,
            ) = match cmd {
                PackCommand::Install { request, reply } => {
                    // Pro gate (consistency with CLI): packs require Pro tier.
                    let license = load_license(Some(&license_path()));
                    let res = if let Err(e) = require_pro_for_pack_ops(&license) {
                        Err(format!("pack install aborted via control plane: {e}"))
                    } else {
                        let origin = request.origin_label().to_string();
                        match request.signed_pack() {
                            Ok(signed) => match packs_worker_manager.install(signed).await {
                                Ok(()) => match packs_worker_manager.snapshot_engine(payload_secret.as_deref()).await {
                                    Ok(new_engine) => {
                                        // Atomic rebase (synchronous helper, no await →
                                        // the std guard never crosses the `await` Send):
                                        // the pack's rules become the BASE and the
                                        // operator's policy is re-applied on top, so
                                        // an install does not wipe the custom rules or
                                        // overrides (fix review v6.1).
                                        match rebase_live_engine(&engine_control_worker, &policy_source, &new_engine) {
                                            Ok(rules) => {
                                                tracing::info!(pack_origin = %origin, rules, "pack installed via control plane");
                                                Ok(format!("pack installed (hot-reload): engine now has {rules} rules"))
                                            }
                                            Err(e) => Err(format!("policy rebase failed after install: {e}")),
                                        }
                                    }
                                    Err(e) => Err(format!("snapshot engine failed: {e}")),
                                },
                                Err(e) => Err(e),
                            },
                            Err(e) => Err(e.to_string()),
                        }
                    };
                    (reply, res)
                }
                PackCommand::Rollback { reply } => {
                    // Pro gate (finding v6): rollback reactivates a pack
                    // version — a Pro benefit, same as install. Denied in Free.
                    let license = load_license(Some(&license_path()));
                    let res = match require_pro_for_pack_ops(&license) {
                        Err(e) => Err(format!("pack rollback aborted via control plane: {e}")),
                        Ok(()) => match packs_worker_manager.rollback().await {
                            Ok(()) => match packs_worker_manager.snapshot_engine(payload_secret.as_deref()).await {
                                Ok(new_engine) => {
                                    // Same as install: the operator's policy is
                                    // re-applied over the reverted rules.
                                    match rebase_live_engine(&engine_control_worker, &policy_source, &new_engine) {
                                        Ok(rules) => {
                                            Ok(format!("rollback executed (hot-reload): engine now has {rules} rules"))
                                        }
                                        Err(e) => Err(format!("policy rebase failed after rollback: {e}")),
                                    }
                                }
                                Err(e) => Err(format!("snapshot engine failed: {e}")),
                            },
                            Err(e) => Err(e),
                        },
                    };
                    (reply, res)
                }
                PackCommand::List { reply } => {
                    let packs = packs_worker_manager.list_packs().await;
                    let res = Ok(format!("{} packs installed", packs.len()));
                    (reply, res)
                }
            };
            let _ = outcome.0.send(outcome.1);
        }
    });

    let ctx = Arc::new(ProxyContext {
        config: shared_config.clone(),
        engine: live_engine.clone(),
        redact_options: cerberus_engine::redact::RedactOptions::default(),
        api: ApiContext::with_store_opt(shared_config, store_opt.clone())
            .with_config_path(config_file())
            .with_pack_worker(pack_tx)
            .with_engine(engine_control)
            .with_audit_hash_key(audit_key.clone()),
        last_upstream: Arc::new(std::sync::Mutex::new(None)),
    });

    // F4 (dev feedback): the daemon watches the in-memory event buffer of
    // the control plane (`ApiContext.events`) and emits one-to-one feedback
    // for each intervention (block/redact/warn) that is logged. The buffer's
    // Arc is captured HERE, before moving `ctx` to the proxies.
    let api_events = ctx.api.events.clone();
    let mut interventions = crate::feedback_ux::InterventionWatcher::new();

    let addr: std::net::SocketAddr = config.listen.parse().map_err(|e| format!("invalid address: {e}"))?;
    let (actual, proxy_handle) = spawn_managed_proxy(addr, ctx.clone())
        .await
        .map_err(|e| format!("proxy error: {e}"))?;
    let mut forward_handle = if let Some(mitm_config) = mitm_config {
        match spawn_forward_proxy(mitm_config, ctx.clone()).await {
            Ok((forward_addr, handle)) => {
                println!("Cerberus MITM opt-in running on {forward_addr} (CONNECT exact allowlist)");
                Some(handle)
            }
            Err(error) => {
                let _ = proxy_handle.shutdown(Duration::from_secs(1)).await;
                return Err(format!("MITM opt-in proxy error: {error}"));
            }
        }
    } else {
        println!("MITM: disabled (default); reverse proxy only");
        None
    };

    // Write PID
    let pid = std::process::id();
    fs::write(pid_path(), pid.to_string()).map_err(|e| format!("cannot write PID: {e}"))?;
    if let Err(e) = persist_endpoint(actual, pid) {
        remove_runtime_files();
        if let Some(handle) = forward_handle.take() {
            let _ = handle.shutdown(Duration::from_secs(1)).await;
        }
        let _ = proxy_handle.shutdown(Duration::from_secs(1)).await;
        return Err(e);
    }

    println!("Cerberus proxy running on {actual}");
    println!("Cerberus started on {actual} (waiting for stop signals)");

    // ─── G) Graceful loop: Ctrl+C / SIGTERM / pid file removed → flush+close.
    // The signal future is resolved OUTSIDE the `tokio::select!` (the macro
    // does not accept `#[cfg]` in arms; on non-unix the SIGTERM arm is
    // `pending()`).
    #[cfg(unix)]
    let mut term_signal = tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
        .map_err(|e| format!("cannot install SIGTERM handler: {e}"))?;
    let ctrl_c = tokio::signal::ctrl_c();
    #[cfg(unix)]
    let sigterm = term_signal.recv();
    #[cfg(not(unix))]
    let sigterm = std::future::pending::<Option<()>>();
    tokio::pin!(ctrl_c);
    tokio::pin!(sigterm);

    // F4 (dev feedback): each tick (1 s), drain new interventions →
    // desktop notification (rate 1/sec) + CLI line as fallback.
    let shutdown: bool = loop {
        tokio::select! {
            _ = &mut ctrl_c => {
                println!("stop signal (SIGINT) received");
                break true;
            }
            _ = &mut sigterm => {
                println!("stop signal (SIGTERM) received");
                break true;
            }
            () = tokio::time::sleep(Duration::from_secs(1)) => {
                if !is_running() {
                    println!("pid file removed — external stop requested");
                    break true;
                }
                // Each tick (1 s), drain new interventions → desktop
                // notification (rate 1/sec) + CLI line as fallback.
                crate::feedback_ux::emit_interventions(&api_events, &mut interventions).await;
            }
        }
    };
    let _ = shutdown;

    // First we close admission and drain requests: no handler can enqueue
    // audit after the store barrier.
    if let Some(handle) = forward_handle {
        if let Err(e) = handle.shutdown(Duration::from_secs(5)).await {
            eprintln!("MITM forward proxy: forced close during shutdown: {e}");
        } else {
            println!("MITM forward proxy: admission closed and tunnels drained");
        }
    }
    if let Err(e) = proxy_handle.shutdown(Duration::from_secs(5)).await {
        eprintln!("proxy: forced close during shutdown: {e}");
    } else {
        println!("proxy: admission closed and requests drained");
    }

    // After the signal: durable flush of the audit store (B) before dying.

    // After the stop signal: durable flush of the audit store (B).
    // If a flush fails, the daemon does NOT announce success (fix review v5
    // #4): audit loss is reported as an error, not as a clean shutdown.
    if let Some(store) = store_opt {
        store.begin_closing();
        match store.flush_durable().await {
            Ok(()) => println!("audit store: durable flush completed"),
            Err(e) => {
                eprintln!("audit store: flush error on shutdown: {e}");
                remove_runtime_files();
                return Err(format!("Cerberus stopped with audit error: {e}"));
            }
        }
        match store.close().await {
            Ok(()) => println!("audit store: writer closed"),
            Err(e) => {
                eprintln!("audit store: close error: {e}");
                remove_runtime_files();
                return Err(format!("Cerberus stopped with audit close error: {e}"));
            }
        }
    }
    remove_runtime_files();
    println!("Cerberus stopped (graceful)");
    Ok("Cerberus stopped (graceful, mutation flushed)".to_string())
}

