/// `cerberus pack install <signed.json>` — verifies the signature against
/// `CERBERUS_PACK_TRUST_ROOT` and merges the rules into the active engine.
/// Gated by license: packs require Pro tier (open-core).
///
/// # Errors
///
/// Error if the license is not Pro, the pack is invalid, there is no trust
/// root, or the rules do not compile.
pub(crate) async fn pack_install(pack_file: &str) -> Result<String, String> {
    let license = load_license(Some(&license_path()));
    require_pro_for_pack_ops(&license).map_err(|e| format!("pack install aborted: {e}"))?;
    let (audit_key, _) = resolve_audit_key();
    let packs = open_packs_manager(&audit_key)?;
    if let Some(root) = env_nonempty("CERBERUS_PACK_TRUST_ROOT") {
        // Rehydrate what is installed (engine history) before adding the new one.
        packs.load_installed_from_dir(&root).await?;
    }
    let before = packs.engine().lock().await.num_rules();
    let signed = PackManager::load_pack_from_file(pack_file)?;
    // `install` requires CERBERUS_PACK_TRUST_ROOT (fail-closed if missing).
    packs.install(signed).await?;
    let after = packs.engine().lock().await.num_rules();
    Ok(format!("pack installed: engine rules {before} → {after}"))
}

/// `cerberus pack list` — lists the signed packs present in
/// `~/.cerberus/packs` and their verification status against the trust root.
///
/// # Errors
///
/// Returns an error only if the directory cannot be read.
pub(crate) fn pack_list() -> Result<String, String> {
    let (audit_key, _) = resolve_audit_key();
    let _ = open_packs_manager(&audit_key)?; // ensures the packs layout (or fails fast).
    let dir = packs_dir();
    let mut entries = Vec::new();
    for entry in fs::read_dir(&dir).map_err(|e| format!("cannot read packs dir {}: {e}", dir.display()))? {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().is_some_and(|e| e == "json") {
            entries.push(path);
        }
    }
    if entries.is_empty() {
        return Ok("no rule packs found in ~/.cerberus/packs.".to_string());
    }
    entries.sort();
    let root = env_nonempty("CERBERUS_PACK_TRUST_ROOT");
    let mut out = String::from("Rule packs:\n");
    for path in entries {
        let name = match PackManager::load_pack_from_file(&path) {
            Ok(signed) => {
                let verified = root
                    .as_deref()
                    .is_some_and(|r| signed.verify_with_trusted_root(r).is_ok());
                let pack = root.as_deref().and_then(|r| signed.extract_with_root(r).ok());
                let label = pack.map_or_else(
                    || name_from_path(&path),
                    |p| format!("{} v{}", p.metadata.name, p.metadata.version),
                );
                match (root.is_some(), verified) {
                    (true, true) => format!("  {label} ✓ valid signature"),
                    (true, false) => format!("  {label} ✗ invalid signature (rejected at boot)"),
                    (false, _) => format!("  {label} unverified (missing CERBERUS_PACK_TRUST_ROOT)"),
                }
            }
            Err(e) => format!("  {} (invalid: {e})", name_from_path(&path)),
        };
        out.push_str(&name);
        out.push('\n');
    }
    Ok(out)
}

/// Pro gate for rule pack operations (finding v6): install and rollback
/// mutate the active engine (Pro benefit). list is read-only and stays free.
fn require_pro_for_pack_ops(license: &LicenseManager) -> Result<(), String> {
    if license.is_pro() {
        Ok(())
    } else {
        Err("rule packs require a Pro license (open-core). Visit 'cerberus license'.".to_string())
    }
}

/// Rebase the proxy's active engine at runtime (hot-reload, fix review v5 +
/// v6.1): the rules of `new_engine` (defaults + packs) become the BASE and
/// the operator's persisted policy (categories, overrides, and custom rules)
/// is re-applied on top.
///
/// **Synchronous** helper on purpose: the std `RwLock` guard never crosses an
/// `await` (the worker future must remain `Send`).
///
/// Returns the number of rules of the newly activated engine.
fn rebase_live_engine(
    control: &cerberus_proxy::detection_policy::EngineControl,
    policy_source: &RwLock<ProxyConfig>,
    new_engine: &CompiledEngine,
) -> Result<usize, String> {
    // Holding the read-lock until the rebase finishes serializes this
    // publication with `commit_policy`, which holds the write-lock during
    // compile → persist → publish. If we cloned the policy and released the
    // lock earlier, a concurrent PUT could publish old-base/new-policy
    // and then this worker overwrite it with new-base/old-policy.
    let cfg = policy_source.read().unwrap_or_else(std::sync::PoisonError::into_inner);
    control.rebase(new_engine.rules().to_vec(), &cfg.policy)
}

/// Name (without extension) of a pack file for `pack list`.
fn name_from_path(path: &std::path::Path) -> String {
    path.file_name().and_then(|s| s.to_str()).map_or_else(
        || path.display().to_string(),
        |s| s.trim_end_matches(".json").to_string(),
    )
}

/// `cerberus pack rollback` — reverts to the previous engine (last install).
///
/// # Errors
///
/// Returns an error if there is no engine history to revert.
pub(crate) async fn pack_rollback() -> Result<String, String> {
    // Pro gate (finding v6): rollback reactivates a pack version, a Pro
    // benefit also in local mode without daemon (open-core).
    let license = load_license(Some(&license_path()));
    require_pro_for_pack_ops(&license).map_err(|e| format!("pack rollback aborted: {e}"))?;
    let (audit_key, _) = resolve_audit_key();
    let packs = open_packs_manager(&audit_key)?;
    if let Some(root) = env_nonempty("CERBERUS_PACK_TRUST_ROOT") {
        packs.load_installed_from_dir(&root).await?;
    }
    packs.rollback().await?;
    let rules = packs.engine().lock().await.num_rules();
    Ok(format!("pack rollback executed: engine rules {rules}"))
}

/// Stop the daemon (F4 cross-platform): delegates to
/// `platform::stop_process_graceful` — on unix it sends **SIGTERM** (not
/// SIGKILL) so the daemon does the graceful flush+close and force-kills only
/// if the process does not exit in ~5s; on windows `taskkill` without `/F`
/// first and `/F` as fallback. On all 3 platforms it cleans the pid file and
/// the endpoint file.
///
/// # Errors
///
/// Returns an error if there is no PID file or the process cannot be killed.
pub(crate) fn stop() -> Result<String, String> {
    let pid_path = pid_path();
    if !pid_path.exists() {
        return Err("Cerberus is not running (no PID file).".to_string());
    }

    let pid_str = fs::read_to_string(&pid_path).map_err(|e| format!("cannot read PID: {e}"))?;
    let pid: u32 = pid_str.trim().parse().map_err(|e| format!("invalid PID: {e}"))?;

    // Centralized in `platform` (a single cross-platform binary): on unix
    // SIGTERM → wait ≤5s → SIGKILL; on windows taskkill without /F → wait
    // ≤5s → taskkill /F. Shared shutdown loop, not duplicated.
    platform::stop_process_graceful(pid)?;

    remove_runtime_files();
    Ok(format!("Cerberus stopped (PID {pid})."))
}

/// Is the process with `pid` still alive? (delegated to
/// `platform::process_alive`: `kill -0` on unix,
/// `tasklist /FI "PID eq N"` on Windows).
fn process_alive(pid: u32) -> bool {
    platform::process_alive(pid)
}

/// Show the daemon status.
#[must_use]
pub(crate) fn status() -> String {
    if !pid_path().exists() {
        return format!("Cerberus: {}", console_style("STOPPED", "red"));
    }
    let pid_str = fs::read_to_string(pid_path()).unwrap_or_default();
    let pid = pid_str.trim();

    if is_running() {
        format!("Cerberus: {} (PID {})", console_style("RUNNING", "green"), pid)
    } else {
        remove_runtime_files();
        format!("Cerberus: {} (PID {pid} stale)", console_style("STOPPED", "red"))
    }
}

/// Is the daemon running? (pid file + live process).
pub(crate) fn is_running() -> bool {
    let pid_path = pid_path();
    if !pid_path.exists() {
        return false;
    }
    let Ok(pid_str) = fs::read_to_string(&pid_path) else {
        return false;
    };
    let Ok(pid) = pid_str.trim().parse::<u32>() else {
        return false;
    };
    process_alive(pid)
}

/// Apply console style (basic ANSI).
fn console_style(text: &str, color: &str) -> String {
    match color {
        "green" => format!("\x1b[32m{text}\x1b[0m"),
        "red" => format!("\x1b[31m{text}\x1b[0m"),
        "yellow" => format!("\x1b[33m{text}\x1b[0m"),
        _ => text.to_string(),
    }
}

